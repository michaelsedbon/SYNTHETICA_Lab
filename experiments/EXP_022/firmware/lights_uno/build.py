#!/usr/bin/env python3
"""Build + flash lights_uno firmware for a specific relay-controller device.

Reads `lights_configs.yaml` next to this script, generates `config.h`, then
calls `arduino-cli` to compile and (optionally) upload. The same firmware
(`lights_uno.ino`) supports any number of channels (1..20) on any digital-pin
layout — per-device configuration lives in the YAML.

Layout the script expects (flat — arduino-cli compiles the whole sketch dir):

    lights_uno/
    ├── lights_configs.yaml    # per-device parameters
    ├── build.py               # ← you are here
    ├── lights_uno.ino         # canonical firmware source
    └── config.h               # GENERATED by this script — gitignored

Usage:
    python3 build.py LIGHTS_1               # compile + upload to LIGHTS_1
    python3 build.py LIGHTS_2 --no-upload   # compile only
    python3 build.py LIGHTS_1 --port /dev/cu.usbmodem3   # override upload port

The Arduino can be Uno or Nano (any ATmega328P with USB serial). Bootloader
varies by board — we try in order: arduino:avr:uno (115200, optiboot, real Uno
or Uno-clone), arduino:avr:nano:cpu=atmega328 (115200, new-bootloader Nano),
arduino:avr:nano:cpu=atmega328old (57600, legacy Nano).
"""
import argparse
import os
import subprocess
import sys

try:
    import yaml
except ImportError:
    sys.exit("PyYAML is required. Install with: pip3 install pyyaml")


HERE = os.path.dirname(os.path.abspath(__file__))
CONFIG_FILE = os.path.join(HERE, "lights_configs.yaml")
CONFIG_H = os.path.join(HERE, "config.h")
FQBN_BUILD = "arduino:avr:uno"
FQBN_UPLOAD_CANDIDATES = [
    "arduino:avr:uno",                       # 115200 baud — Uno + most Uno clones (optiboot)
    "arduino:avr:nano:cpu=atmega328",        # 115200 baud — new-bootloader Nano
    "arduino:avr:nano:cpu=atmega328old",     # 57600  baud — legacy Nano
]


def load_configs() -> dict:
    if not os.path.exists(CONFIG_FILE):
        sys.exit(f"lights_configs.yaml not found at {CONFIG_FILE}")
    with open(CONFIG_FILE) as f:
        return yaml.safe_load(f) or {}


def render_config_h(device_id: str, cfg: dict) -> str:
    required = ["num_channels", "pins", "active_low"]
    missing = [k for k in required if k not in cfg]
    if missing:
        sys.exit(f"lights_configs.yaml[{device_id}] missing keys: {missing}")
    pins = cfg["pins"]
    if len(pins) != cfg["num_channels"]:
        sys.exit(f"{device_id}: num_channels={cfg['num_channels']} but pins[] has {len(pins)} entries")
    if not all(isinstance(p, int) and 0 <= p <= 19 for p in pins):
        sys.exit(f"{device_id}: every pin must be int 0..19 (D0..D13 + A0..A5 mapped to 14..19)")
    if len(set(pins)) != len(pins):
        sys.exit(f"{device_id}: duplicate pins in list — every channel must be unique")
    desc = cfg.get("description", "(no description)")
    desc_escaped = desc.replace('"', '\\"')
    pin_list = ", ".join(str(p) for p in pins)
    active_low = 1 if cfg["active_low"] else 0
    return f"""// AUTO-GENERATED from lights_configs.yaml — do not edit by hand.
// Device: {device_id} — {desc}
#pragma once

#define DEVICE_ID            "{device_id}"
#define DEVICE_DESCRIPTION   "{desc_escaped}"
#define NUM_RELAYS           {cfg['num_channels']}
#define ACTIVE_LOW           {active_low}
#define RELAY_PINS_INIT      {{ {pin_list} }}
"""


def write_config_h(content: str) -> None:
    with open(CONFIG_H, "w") as f:
        f.write(content)


def run(cmd: list, **kwargs) -> None:
    print("+ " + " ".join(cmd))
    subprocess.run(cmd, check=True, **kwargs)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("device_id", help="Device ID — must be a top-level key in lights_configs.yaml")
    ap.add_argument("--no-upload", action="store_true", help="Compile but skip flashing")
    ap.add_argument("--port", help="Override the upload port from lights_configs.yaml")
    args = ap.parse_args()

    configs = load_configs()
    if args.device_id not in configs:
        sys.exit(f"{args.device_id!r} not in lights_configs.yaml. Available: {list(configs)}")
    cfg = configs[args.device_id]
    print(f"Building lights firmware for {args.device_id} — {cfg['num_channels']} ch, "
          f"pins={cfg['pins']}, active_low={cfg['active_low']}")

    write_config_h(render_config_h(args.device_id, cfg))

    run(["arduino-cli", "compile", "--fqbn", FQBN_BUILD, HERE])
    if args.no_upload:
        print("--no-upload set — skipping flash.")
        return
    port = args.port or cfg.get("port")
    if not port:
        sys.exit("No upload port — set `port:` in lights_configs.yaml or pass --port")

    last_err = None
    for fqbn in FQBN_UPLOAD_CANDIDATES:
        try:
            print(f"Trying upload with FQBN={fqbn}")
            run(["arduino-cli", "upload", "-p", port, "--fqbn", fqbn, HERE])
            print(f"Flashed {args.device_id} on {port} (bootloader: {fqbn.rsplit('=', 1)[-1].rsplit(':', 1)[-1]}).")
            return
        except subprocess.CalledProcessError as e:
            last_err = e
            print(f"  upload with {fqbn} failed; trying next candidate...")
    sys.exit(f"All bootloader candidates failed. Last error: {last_err}")


if __name__ == "__main__":
    main()
