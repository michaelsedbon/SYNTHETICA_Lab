#!/usr/bin/env python3
"""Build + flash motor_nano firmware for a specific motor.

Reads `motor_configs.yaml` next to this script, generates `<sketch>/config.h`,
then calls `arduino-cli` to compile and (optionally) upload.

Layout the script expects (all in one flat directory — arduino-cli compiles
the sketch dir, so a `src/` subdir would also be picked up and cause duplicate
`setup()/loop()` errors):

    motor_nano/
    ├── motor_configs.yaml     # per-motor parameters (this script reads it)
    ├── build.py               # ← you are here
    ├── motor_nano.ino         # canonical firmware source
    └── config.h               # GENERATED by this script — gitignored

Usage:
    python3 build.py MOTOR_1               # compile + upload to MOTOR_1
    python3 build.py MOTOR_1 --no-upload   # compile only
    python3 build.py MOTOR_1 --port /dev/ttyACM7   # override upload port

Designed to run on the LattePanda (where arduino-cli + the AVR core live)
but works anywhere arduino-cli is in the PATH.
"""
import argparse
import os
import subprocess
import sys

try:
    import yaml
except ImportError:
    sys.exit("PyYAML is required. Install with: pip3 install pyyaml")


HERE = os.path.dirname(os.path.abspath(__file__))
CONFIG_FILE = os.path.join(HERE, "motor_configs.yaml")
SKETCH_INO = os.path.join(HERE, "motor_nano.ino")  # arduino-cli sketch entry
CONFIG_H = os.path.join(HERE, "config.h")
FQBN_BUILD = "arduino:avr:nano:cpu=atmega328"
# Bootloader varies by Nano vintage. Newer clones (and modern restocks) ship
# with the optiboot "new" bootloader at 115200 baud; older clones ship with
# the legacy bootloader at 57600 baud. We try the old one first, then fall
# back to the new one — both ATmega328P, same firmware, just upload protocol.
FQBN_UPLOAD_CANDIDATES = [
    "arduino:avr:nano:cpu=atmega328old",  # 57600 baud — legacy clones
    "arduino:avr:nano:cpu=atmega328",     # 115200 baud — newer / new-bootloader
]


def load_configs() -> dict:
    if not os.path.exists(CONFIG_FILE):
        sys.exit(f"motor_configs.yaml not found at {CONFIG_FILE}")
    with open(CONFIG_FILE) as f:
        return yaml.safe_load(f) or {}


def render_config_h(motor_id: str, cfg: dict) -> str:
    required = [
        "max_steps", "pin_step", "pin_dir", "pin_sensor", "home_dir",
        "cal_speed_down", "cal_speed_up", "cal_chunk_steps", "cal_pause_ms",
    ]
    missing = [k for k in required if k not in cfg]
    if missing:
        sys.exit(f"motor_configs.yaml[{motor_id}] missing keys: {missing}")
    default_speed = cfg.get("default_speed", 2000)
    default_accel = cfg.get("default_accel", 1000)
    cal_enabled = 1 if cfg.get("cal_enabled", True) else 0
    desc = cfg.get("description", "(no description)")
    desc_escaped = desc.replace('"', '\\"')
    return f"""// AUTO-GENERATED from motor_configs.yaml — do not edit by hand.
// Motor: {motor_id} — {desc}
#pragma once

#define DEVICE_ID            "{motor_id}"
#define DEVICE_DESCRIPTION   "{desc_escaped}"
#define PIN_STEP             {cfg['pin_step']}
#define PIN_DIR              {cfg['pin_dir']}
#define PIN_SENSOR           {cfg['pin_sensor']}
#define HOME_DIR             ({cfg['home_dir']})
#define DEFAULT_MAX_STEPS    {cfg['max_steps']}L
#define CAL_ENABLED          {cal_enabled}
#define CAL_SPEED_DOWN       {float(cfg['cal_speed_down']):.1f}
#define CAL_SPEED_UP         {float(cfg['cal_speed_up']):.1f}
#define CAL_CHUNK_STEPS      {cfg['cal_chunk_steps']}L
#define CAL_PAUSE_MS         {cfg['cal_pause_ms']}UL
#define DEFAULT_SPEED        {float(default_speed):.1f}
#define DEFAULT_ACCEL        {float(default_accel):.1f}
"""


def write_config_h(content: str) -> None:
    with open(CONFIG_H, "w") as f:
        f.write(content)


def run(cmd: list, **kwargs) -> None:
    print("+ " + " ".join(cmd))
    subprocess.run(cmd, check=True, **kwargs)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("motor_id", help="Motor ID — must be a top-level key in motor_configs.yaml")
    ap.add_argument("--no-upload", action="store_true", help="Compile but skip flashing")
    ap.add_argument("--port", help="Override the upload port from motor_configs.yaml")
    args = ap.parse_args()

    configs = load_configs()
    if args.motor_id not in configs:
        sys.exit(f"{args.motor_id!r} not in motor_configs.yaml. Available: {list(configs)}")
    cfg = configs[args.motor_id]
    print(f"Building firmware for {args.motor_id} — max_steps={cfg['max_steps']}")

    write_config_h(render_config_h(args.motor_id, cfg))

    run(["arduino-cli", "compile", "--fqbn", FQBN_BUILD, HERE])
    if args.no_upload:
        print("--no-upload set — skipping flash.")
        return
    port = args.port or cfg.get("port")
    if not port:
        sys.exit("No upload port — set `port:` in motor_configs.yaml or pass --port")

    last_err = None
    for fqbn in FQBN_UPLOAD_CANDIDATES:
        try:
            print(f"Trying upload with FQBN={fqbn}")
            run(["arduino-cli", "upload", "-p", port, "--fqbn", fqbn, HERE])
            print(f"Flashed {args.motor_id} on {port} (bootloader: {fqbn.rsplit('=', 1)[-1]}).")
            return
        except subprocess.CalledProcessError as e:
            last_err = e
            print(f"  upload with {fqbn} failed; trying next candidate...")
    sys.exit(f"All bootloader candidates failed. Last error: {last_err}")


if __name__ == "__main__":
    main()
